//! End-to-end MVP test: triangle mesh -> slicer -> G-code export.

use polyforge_print::{
    generate_gcode, MeshTriangles, PrinterProfile, SliceSettings, SlicerEngine, Triangle, Vec3,
};

/// Axis-aligned cube centred on the origin, as a triangle soup (mm).
fn cube(size_mm: f64) -> MeshTriangles {
    let s = size_mm * 0.5;
    let v = [
        Vec3::new(-s, -s, -s),
        Vec3::new(s, -s, -s),
        Vec3::new(s, s, -s),
        Vec3::new(-s, s, -s),
        Vec3::new(-s, -s, s),
        Vec3::new(s, -s, s),
        Vec3::new(s, s, s),
        Vec3::new(-s, s, s),
    ];
    let faces = [
        [0, 1, 2, 3],
        [5, 4, 7, 6],
        [4, 0, 3, 7],
        [1, 5, 6, 2],
        [3, 2, 6, 7],
        [4, 5, 1, 0],
    ];
    let mut tris = Vec::new();
    for f in faces {
        tris.push(Triangle::new(v[f[0]], v[f[1]], v[f[2]]));
        tris.push(Triangle::new(v[f[0]], v[f[2]], v[f[3]]));
    }
    tris
}

#[test]
fn slice_and_export_gcode() {
    let printer = PrinterProfile::create_builtin("generic_marlin").expect("builtin printer");
    let mut settings = printer.default_settings.clone();
    settings.infill_density = 0.2;

    let slice = SlicerEngine::new().slice(&cube(20.0), &settings, &printer);

    assert!(slice.success, "slice errors: {:?}", slice.errors);
    assert!(slice.total_layers >= 95, "layers: {}", slice.total_layers);
    assert!(slice.filament_used > 0.0, "filament must be positive");
    assert!(slice.print_time > 0.0, "print time must be positive");
    assert_eq!(slice.layers.len(), slice.total_layers);

    let gcode = generate_gcode(&slice, &printer, &settings);
    assert!(gcode.contains("Generated by PolyForge"));
    assert!(gcode.contains("G28"));
    assert!(gcode.contains("M84"));
    assert!(gcode.lines().count() > 200);
}

#[test]
fn oversized_model_is_rejected() {
    let printer = PrinterProfile::create_builtin("prusa_mini").expect("builtin printer");
    let settings = SliceSettings::default();

    let slice = SlicerEngine::new().slice(&cube(400.0), &settings, &printer);
    assert!(!slice.success);
    assert!(!slice.errors.is_empty());
}

#[test]
fn all_builtin_profiles_are_valid() {
    for profile in PrinterProfile::builtin_profiles() {
        assert!(
            profile.validate().is_ok(),
            "profile {} invalid: {:?}",
            profile.id,
            profile.validate()
        );
    }
}
