//! G-code generation from a `SliceInfo`.
//!
//! Port of ksengine's `GCodeGenerator`: firmware-aware header/startup,
//! per-layer perimeter/infill/support/brim moves with extrusion maths,
//! retraction and z-hop, followed by the shutdown sequence.

use crate::profile::PrinterProfile;
use crate::types::{
    BoundingBox, GCodeFlavor, LayerSlice, LayerSlices, Polygons2D, SliceInfo, SliceSettings,
};

/// Emits G-code while tracking the current machine state.
#[derive(Debug, Clone)]
pub struct GCodeGenerator {
    x: f64,
    y: f64,
    z: f64,
    e: f64,
    feedrate: f64,
    relative_extrusion: bool,
    total_layers: usize,
    total_filament: f64,
    total_time: f64,
}

impl Default for GCodeGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl GCodeGenerator {
    pub fn new() -> Self {
        Self {
            x: 0.0,
            y: 0.0,
            z: 0.0,
            e: 0.0,
            feedrate: 0.0,
            relative_extrusion: false,
            total_layers: 0,
            total_filament: 0.0,
            total_time: 0.0,
        }
    }

    /// Generate the whole program as a single string.
    pub fn generate(
        &mut self,
        slice_info: &SliceInfo,
        printer: &PrinterProfile,
        settings: &SliceSettings,
    ) -> String {
        self.reset();
        self.total_layers = slice_info.layers.len();
        self.total_filament = slice_info.filament_used;
        self.total_time = slice_info.print_time;

        let mut out = String::new();
        self.write_header(&mut out, printer, settings, &slice_info.bounding_box);
        out.push('\n');
        self.write_startup(&mut out, printer, settings);
        out.push('\n');

        for (i, layer) in slice_info.layers.iter().enumerate() {
            if i > 0 {
                self.write_layer_change(&mut out, i, printer, settings);
            }
            self.write_layer(&mut out, layer, settings);
        }

        self.write_shutdown(&mut out, printer, settings);
        out.push('\n');
        self.write_footer(&mut out, settings);
        out
    }

    fn reset(&mut self) {
        self.x = 0.0;
        self.y = 0.0;
        self.z = 0.0;
        self.e = 0.0;
        self.feedrate = 0.0;
        self.relative_extrusion = false;
    }

    // ---- Header / footer -------------------------------------------------

    fn write_header(
        &self,
        out: &mut String,
        printer: &PrinterProfile,
        settings: &SliceSettings,
        bounds: &BoundingBox,
    ) {
        self.comment(out, "Generated by PolyForge 3D print module");
        self.comment(out, &format!("Printer: {} ({})", printer.name, printer.id));
        let profile = if settings.output_filename.is_empty() {
            "default"
        } else {
            &settings.output_filename
        };
        self.comment(out, &format!("Slicing profile: {profile}"));
        self.comment(out, &format!("Layers: {}", self.total_layers));
        let size = bounds.size();
        self.comment(
            out,
            &format!("Bounds: X{:.1} Y{:.1} Z{:.1}", size.x, size.y, size.z),
        );
        self.comment(out, &format!("Estimated time: {:.0}s", self.total_time));
        self.comment(
            out,
            &format!("Estimated filament: {:.1}mm", self.total_filament),
        );
        self.comment(out, "");

        match printer.gcode_flavor {
            GCodeFlavor::Klipper | GCodeFlavor::RepRap => {
                self.line(out, "G21 ; Units: millimeters");
                self.line(out, "G90 ; Absolute positioning");
                self.line(out, "M83 ; Relative extrusion");
            }
            _ => {
                self.line(out, "G21 ; Units: millimeters");
                self.line(out, "G90 ; Absolute positioning");
                self.line(out, "M82 ; Absolute extrusion");
            }
        }
    }

    fn write_footer(&self, out: &mut String, _settings: &SliceSettings) {
        self.comment(out, "");
        self.comment(out, "Print complete");
        self.comment(
            out,
            &format!("Total filament used: {:.2}mm", self.total_filament),
        );
        self.comment(
            out,
            &format!("Estimated print time: {:.0}s", self.total_time),
        );
    }

    fn write_startup(
        &mut self,
        out: &mut String,
        printer: &PrinterProfile,
        settings: &SliceSettings,
    ) {
        self.comment(out, "=== STARTUP ===");

        let startup = if printer.start_gcode.is_empty() {
            default_startup_gcode(printer, settings)
        } else {
            apply_placeholders(&printer.start_gcode, printer, settings)
        };
        out.push_str(&startup);
        out.push('\n');

        if !startup.contains("M104") && !startup.contains("M109") {
            self.line(
                out,
                &format!("M109 S{} ; Wait for hotend", settings.nozzle_temp),
            );
        }
        if !startup.contains("M140") && !startup.contains("M190") {
            self.line(out, &format!("M190 S{} ; Wait for bed", settings.bed_temp));
        }
    }

    fn write_shutdown(
        &mut self,
        out: &mut String,
        printer: &PrinterProfile,
        settings: &SliceSettings,
    ) {
        self.comment(out, "=== SHUTDOWN ===");
        let shutdown = if printer.end_gcode.is_empty() {
            default_shutdown_gcode(printer, settings)
        } else {
            apply_placeholders(&printer.end_gcode, printer, settings)
        };
        out.push_str(&shutdown);
        out.push('\n');
    }

    // ---- Layers ----------------------------------------------------------

    fn write_layer_change(
        &mut self,
        _out: &mut String,
        layer_index: usize,
        printer: &PrinterProfile,
        settings: &SliceSettings,
    ) {
        let _ = (printer, settings, layer_index);
        // Reserved for printer-specific layer-change scripts (none by default).
    }

    fn write_layer(&mut self, out: &mut String, layer: &LayerSlice, settings: &SliceSettings) {
        if layer.is_first_layer {
            self.comment(
                out,
                &format!("=== LAYER {} (FIRST LAYER) ===", layer.layer_index + 1),
            );
        } else if layer.is_last_layer {
            self.comment(
                out,
                &format!("=== LAYER {} (LAST LAYER) ===", layer.layer_index + 1),
            );
        } else {
            self.comment(out, &format!("=== LAYER {} ===", layer.layer_index + 1));
        }
        self.comment(out, &format!("Z = {:.3}", layer.z));

        self.move_to(
            out,
            self.x,
            self.y,
            layer.z,
            self.feed(settings.travel_speed),
        );

        if settings.cooling_enabled {
            let fan = if (layer.layer_index as f64) < settings.fan_start_layer {
                settings.initial_fan_speed
            } else {
                settings.fan_speed
            };
            self.set_fan(out, fan);
        }

        if !layer.perimeters.is_empty() {
            self.comment(out, "--- Perimeters ---");
            self.write_perimeters(out, &layer.perimeters, settings);
        }

        if !layer.infill.is_empty() {
            self.comment(out, "--- Infill ---");
            self.set_feedrate(out, self.feed(settings.infill_speed));
            self.write_lines(
                out,
                &layer.infill,
                settings,
                settings.infill_speed,
                settings.layer_height,
            );
        }

        if !layer.support.is_empty() {
            self.comment(out, "--- Support ---");
            self.set_feedrate(out, self.feed(settings.support_speed));
            self.write_lines(
                out,
                &layer.support,
                settings,
                settings.support_speed,
                settings.layer_height,
            );
        }

        if layer.is_first_layer && !layer.brim.is_empty() {
            self.comment(out, "--- Brim/Skirt ---");
            self.set_feedrate(out, self.feed(settings.initial_layer_speed));
            self.write_lines(
                out,
                &layer.brim,
                settings,
                settings.initial_layer_speed,
                settings.initial_layer_height,
            );
        }
    }

    fn write_perimeters(
        &mut self,
        out: &mut String,
        perimeters: &Polygons2D,
        settings: &SliceSettings,
    ) {
        self.set_feedrate(out, self.feed(settings.outer_wall_speed));

        for poly in perimeters {
            if poly.vertices.len() < 3 {
                continue;
            }
            let start = poly.vertices[0];
            self.travel_to(out, start.x, start.y, self.z);

            let mut prev = start;
            for v in poly.vertices.iter().skip(1) {
                let dist = (*v - prev).length();
                let e = self.extrusion(
                    dist,
                    settings.line_width,
                    settings.layer_height,
                    settings.filament_diameter,
                );
                self.move_to(out, v.x, v.y, self.z, self.feed(settings.outer_wall_speed));
                self.set_e(out, e, settings);
                prev = *v;
            }
            // Close the loop.
            let dist = (start - prev).length();
            let e = self.extrusion(
                dist,
                settings.line_width,
                settings.layer_height,
                settings.filament_diameter,
            );
            self.move_to(
                out,
                start.x,
                start.y,
                self.z,
                self.feed(settings.outer_wall_speed),
            );
            self.set_e(out, e, settings);
        }
    }

    fn write_lines(
        &mut self,
        out: &mut String,
        polys: &Polygons2D,
        settings: &SliceSettings,
        speed: f64,
        height: f64,
    ) {
        for poly in polys {
            if poly.vertices.len() < 2 {
                continue;
            }
            self.travel_to(out, poly.vertices[0].x, poly.vertices[0].y, self.z);
            let mut prev = poly.vertices[0];
            for v in poly.vertices.iter().skip(1) {
                let dist = (*v - prev).length();
                let e = self.extrusion(
                    dist,
                    settings.line_width,
                    height,
                    settings.filament_diameter,
                );
                self.move_to(out, v.x, v.y, self.z, self.feed(speed));
                self.set_e(out, e, settings);
                prev = *v;
            }
        }
    }

    // ---- Low-level movement ---------------------------------------------

    fn move_to(&mut self, out: &mut String, x: f64, y: f64, z: f64, feedrate: f64) {
        let mut parts = String::from("G1");
        if (x - self.x).abs() > 0.001 {
            parts.push_str(&format!(" X{:.3}", x));
        }
        if (y - self.y).abs() > 0.001 {
            parts.push_str(&format!(" Y{:.3}", y));
        }
        if (z - self.z).abs() > 0.001 {
            parts.push_str(&format!(" Z{:.3}", z));
        }
        if feedrate > 0.0 && (feedrate - self.feedrate).abs() > 1.0 {
            parts.push_str(&format!(" F{:.0}", feedrate));
            self.feedrate = feedrate;
        }
        self.line(out, &parts);
        self.x = x;
        self.y = y;
        self.z = z;
    }

    fn travel_to(&mut self, out: &mut String, x: f64, y: f64, z: f64) {
        let feed = if self.feedrate > 0.0 {
            self.feedrate
        } else {
            9000.0
        };
        self.move_to(out, x, y, z, feed);
    }

    /// Emit the extrusion amount for the just-issued move.
    fn set_e(&mut self, out: &mut String, amount: f64, _settings: &SliceSettings) {
        if amount <= 0.0 {
            return;
        }
        if self.relative_extrusion {
            self.line(out, &format!("G1 E{:.5}", amount));
            self.e += amount;
        } else {
            self.e += amount;
            self.line(out, &format!("G1 E{:.5}", self.e));
        }
        self.total_filament += amount;
    }

    fn set_feedrate(&mut self, out: &mut String, feedrate: f64) {
        if (feedrate - self.feedrate).abs() > 1.0 {
            self.line(out, &format!("G1 F{:.0}", feedrate));
            self.feedrate = feedrate;
        }
    }

    fn set_fan(&mut self, out: &mut String, percent: u8) {
        let s = ((percent as u32 * 255) / 100).min(255);
        self.line(out, &format!("M106 S{s} ; Fan speed {percent}%"));
    }

    fn extrusion(
        &self,
        distance: f64,
        line_width: f64,
        layer_height: f64,
        filament_diameter: f64,
    ) -> f64 {
        if distance <= 0.0 {
            return 0.0;
        }
        let cross_section = line_width * layer_height;
        let filament_area = std::f64::consts::PI * filament_diameter * filament_diameter / 4.0;
        if filament_area <= 0.0 {
            0.0
        } else {
            distance * cross_section / filament_area
        }
    }

    /// Convert mm/s to mm/min.
    fn feed(&self, mm_per_s: f64) -> f64 {
        mm_per_s * 60.0
    }

    fn line(&self, out: &mut String, text: &str) {
        out.push_str(text);
        out.push('\n');
    }

    fn comment(&self, out: &mut String, text: &str) {
        if text.is_empty() {
            out.push('\n');
        } else {
            out.push_str("; ");
            out.push_str(text);
            out.push('\n');
        }
    }
}

/// Generate a full program from a slice in one call.
pub fn generate_gcode(
    slice_info: &SliceInfo,
    printer: &PrinterProfile,
    settings: &SliceSettings,
) -> String {
    GCodeGenerator::new().generate(slice_info, printer, settings)
}

/// Generate G-code straight from a list of layers (no `SliceInfo` needed).
pub fn generate_from_layers(
    layers: &LayerSlices,
    printer: &PrinterProfile,
    settings: &SliceSettings,
) -> String {
    let info = SliceInfo {
        layers: layers.clone(),
        success: true,
        ..Default::default()
    };
    generate_gcode(&info, printer, settings)
}

fn apply_placeholders(script: &str, printer: &PrinterProfile, settings: &SliceSettings) -> String {
    script
        .replace("{nozzle_temp}", &settings.nozzle_temp.to_string())
        .replace("{bed_temp}", &settings.bed_temp.to_string())
        .replace(
            "{print_speed}",
            &format!("{:.0}", settings.print_speed * 60.0),
        )
        .replace(
            "{travel_speed}",
            &format!("{:.0}", settings.travel_speed * 60.0),
        )
        .replace("{bed_max_x}", &format!("{:.1}", printer.build_volume_x))
        .replace("{bed_max_y}", &format!("{:.1}", printer.build_volume_y))
        .replace(
            "{initial_layer_height}",
            &format!("{:.2}", settings.initial_layer_height),
        )
}

fn default_startup_gcode(printer: &PrinterProfile, settings: &SliceSettings) -> String {
    let _ = printer;
    format!(
        "; Default startup\n\
         G21\n\
         G90\n\
         M82\n\
         M104 S{noz}\n\
         M140 S{bed}\n\
         G28\n\
         G1 Z5 F5000\n\
         M190 S{bed}\n\
         M109 S{noz}\n\
         G92 E0\n\
         G1 X10 Y10 Z0.2 F3000\n\
         G1 X100 E15 F1000\n\
         G92 E0",
        noz = settings.nozzle_temp,
        bed = settings.bed_temp,
    )
}

fn default_shutdown_gcode(printer: &PrinterProfile, _settings: &SliceSettings) -> String {
    format!(
        "; Default shutdown\n\
         M104 S0\n\
         M140 S0\n\
         G91\n\
         G1 E-2 F2700\n\
         G1 Z5 F1000\n\
         G90\n\
         G1 X0 Y{max_y} F5000\n\
         M84",
        max_y = printer.build_volume_y,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::profile::PrinterProfile;
    use crate::slicer::SlicerEngine;
    use crate::types::{SliceSettings, Triangle, Vec3};

    fn cube(size: f64) -> crate::types::MeshTriangles {
        let s = size * 0.5;
        let v = [
            Vec3::new(-s, -s, -s),
            Vec3::new(s, -s, -s),
            Vec3::new(s, s, -s),
            Vec3::new(-s, s, -s),
            Vec3::new(-s, -s, s),
            Vec3::new(s, -s, s),
            Vec3::new(s, s, s),
            Vec3::new(-s, s, s),
        ];
        let faces = [
            [0, 1, 2, 3],
            [5, 4, 7, 6],
            [4, 0, 3, 7],
            [1, 5, 6, 2],
            [3, 2, 6, 7],
            [4, 5, 1, 0],
        ];
        let mut tris = Vec::new();
        for f in faces {
            let (a, b, c, d) = (v[f[0]], v[f[1]], v[f[2]], v[f[3]]);
            tris.push(Triangle::new(a, b, c));
            tris.push(Triangle::new(a, c, d));
        }
        tris
    }

    #[test]
    fn gcode_contains_moves_and_heat() {
        let printer = PrinterProfile::create_builtin("generic_marlin").unwrap();
        let settings = SliceSettings::default();
        let info = SlicerEngine::new().slice(&cube(20.0), &settings, &printer);
        assert!(info.success);

        let gcode = generate_gcode(&info, &printer, &settings);
        assert!(gcode.contains("G28"));
        assert!(gcode.contains("M104 S210"));
        assert!(gcode.contains("G1 X"));
        assert!(gcode.contains("M84"));
        assert!(gcode.lines().count() > 100);
    }

    #[test]
    fn klipper_uses_relative_extrusion() {
        let printer = PrinterProfile::create_builtin("generic_klipper").unwrap();
        let settings = printer.default_settings.clone();
        let info = SlicerEngine::new().slice(&cube(10.0), &settings, &printer);
        let gcode = generate_gcode(&info, &printer, &settings);
        assert!(gcode.contains("M83"));
    }
}
